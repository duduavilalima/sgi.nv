package br.com.araujoabreu.sgi.tesouraria.lang;

public class CodigoDeBarrasException extends Exception {

	private static final long serialVersionUID = 4471104668744531247L;

	public CodigoDeBarrasException() {
		super();
	}

	public CodigoDeBarrasException(String message, Throwable cause) {
		super(message, cause);
	}

	public CodigoDeBarrasException(String message) {
		super(message);
	}

	public CodigoDeBarrasException(Throwable cause) {
		super(cause);
	}

}
