package br.com.araujoabreu.sgi.tesouraria.lang;

public class LinhaDigitavelException extends Exception {

	private static final long serialVersionUID = 2994171097528046192L;

	public LinhaDigitavelException() {
		super();
	}

	public LinhaDigitavelException(String message, Throwable cause) {
		super(message, cause);
	}

	public LinhaDigitavelException(String message) {
		super(message);
	}

	public LinhaDigitavelException(Throwable cause) {
		super(cause);
	}

}
