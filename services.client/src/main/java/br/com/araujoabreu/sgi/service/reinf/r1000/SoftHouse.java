package br.com.araujoabreu.sgi.service.reinf.r1000;

public class SoftHouse {
	private String cnpjSoftHouse;
	private String nmRazao;
	private String nmCont;
	private String telefone;
	private String email;

	public String getCnpjSoftHouse() {
		return cnpjSoftHouse;
	}

	public void setCnpjSoftHouse(String cnpjSoftHouse) {
		this.cnpjSoftHouse = cnpjSoftHouse;
	}

	public String getNmRazao() {
		return nmRazao;
	}

	public void setNmRazao(String nmRazao) {
		this.nmRazao = nmRazao;
	}

	public String getNmCont() {
		return nmCont;
	}

	public void setNmCont(String nmCont) {
		this.nmCont = nmCont;
	}

	public String getTelefone() {
		return telefone;
	}

	public void setTelefone(String telefone) {
		this.telefone = telefone;
	}

	public String getEmail() {
		return email;
	}

	public void setEmail(String email) {
		this.email = email;
	}
}
